declare(strict_types=1);

namespace Papastro\Pasway;

/**
 * Fluent channel broadcaster wrapper for Pasway.
 */
class Channel
{
    protected string $name;

    public function __construct(string $name)
    {
        $this->name = $name;
    }

    public function getName(): string
    {
        return $this->name;
    }

    /**
     * Broadcast an event on this channel.
     */
    public function broadcast(string $event, mixed $data = []): bool
    {
        return Pasway::broadcast($this->name, $event, $data);
    }
}
